test('[claude-code-pull R6] undo removes the note and everything slice 6 removes; an edited note is left alone; undo after repeated init still restores every skill', async () => {
  const d = project(), before = snapshot(d);
  await tap(d, ['init', 'claude', '--mode', 'pull']); await tap(d, ['init', 'claude', '--mode', 'pull']); await tap(d, ['init', 'claude', '--mode', 'hook']); await tap(d, ['init', 'claude', '--mode', 'pull']);
  const u = await tap(d, ['init', 'claude', '--undo']);
  assert.equal(u.code, 0); assert.ok(!existsSync(RULES(d))); assert.deepEqual(snapshot(d), before); assert.ok(!existsSync(SETTINGS(d)), 'the settings file init created is removed');
  assert.match((await tap(d, ['init', 'claude', '--undo'])).out, /Nothing to undo/);
  const e = project(); await tap(e, ['init', 'claude', '--mode', 'pull']); writeFileSync(RULES(e), read(RULES(e)) + '\nmy own line\n');
  const u2 = await tap(e, ['init', 'claude', '--undo']);
  assert.match(u2.out, /nib\.md \(changed since init; left alone\)/); assert.ok(existsSync(RULES(e))); assert.ok(existsSync(join(e, '.nib', 'init-claude.json')));
  const clash = project({ '.claude/rules/nib.md': 'something else\n' });
  const c = await tap(clash, ['init', 'claude', '--mode', 'pull']); assert.equal(c.code, 1); assert.match(c.err, /was not written by SkillNib/); assert.equal(read(RULES(clash)), 'something else\n');
});

test('[claude-code-pull R7] the command in the note works from the project directory and from a subdirectory and returns the requested section verbatim', async () => {
  const d = project({ 'AGENTS.md': '# Agents\n' }), sub = join(d, 'a', 'b'); mkdirSync(sub, { recursive: true });
  await tap(d, ['init', 'claude', '--mode', 'pull']);
  const cmd = /`(.+?) ask "<what you need to know>"`/.exec(read(RULES(d)))[1];
  const src = read(FIX, 'acme-incident-report', 'SKILL.md'), want = src.slice(src.indexOf('## Report structure'), src.indexOf('## Blameless language'));
  for (const cwd of [d, sub]) {
    const run = spawnSync('sh', ['-c', `${cmd} ask "incident report structure headings timestamps"`], { cwd, encoding: 'utf8', env: cleanEnv() });
    assert.equal(run.status, 0, run.stderr); assert.ok(run.stdout.includes(want), cwd);
  }
  assert.equal(read(d, 'AGENTS.md'), '# Agents\n');
});

