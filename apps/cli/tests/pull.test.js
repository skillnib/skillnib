import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, existsSync, cpSync, symlinkSync, readdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { main } from '../src/main.js';

const here = dirname(fileURLToPath(import.meta.url)), bin = join(here, '..', 'bin', 'nib.js');
const FIX = join(here, '../../../docs/guide/sample-skills');
const sha = t => createHash('sha256').update(t).digest('hex');
const cleanEnv = extra => { const e = { ...process.env, GITHUB_TOKEN: '', ...extra }; delete e.NODE_TEST_CONTEXT; delete e.NIB_STORE; return e; };
async function tap(cwd, argv, { env = { GITHUB_TOKEN: '', HOME: join(cwd, '.nohome'), PATH: '/usr/bin' }, nibPath = bin } = {}) {
  let out = '', err = '';
  const code = await main(argv, { stdout: { write: s => { out += s; } }, stderr: { write: s => { err += s; } }, cwd, env, nibPath });
  return { code, out, err };
}
const read = (...p) => readFileSync(join(...p), 'utf8');
const RULES = d => join(d, '.claude', 'rules', 'nib.md'), SETTINGS = d => join(d, '.claude', 'settings.local.json');
const skillFiles = d => readdirSync(join(d, '.claude/skills')).map(n => join(d, '.claude/skills', n, 'SKILL.md'));
const snapshot = d => Object.fromEntries(skillFiles(d).map(f => [f, read(f)]));
function project(extra = {}) {
  const d = mkdtempSync(join(tmpdir(), 'pull-'));
  cpSync(FIX, join(d, '.claude', 'skills'), { recursive: true });
  for (const [p, c] of Object.entries(extra)) { mkdirSync(dirname(join(d, p)), { recursive: true }); writeFileSync(join(d, p), c); }
  return d;
}
const instr = d => ['AGENTS.md', 'CLAUDE.md', 'CLAUDE.local.md'].map(f => [f, existsSync(join(d, f)) ? sha(read(d, f)) : null]);

test('[claude-code-pull R1] pull writes the note and drops only the SkillNib hook; hook restores the hook and drops only the note; each is idempotent; bad modes exit 2; dry run writes nothing', async () => {
  const d = project({ '.claude/settings.local.json': JSON.stringify({ permissions: { allow: ['Bash(ls)'] }, hooks: { Stop: [{ hooks: [{ type: 'command', command: 'echo bye' }] }] } }) });
  await tap(d, ['init', 'claude']);
  assert.ok(JSON.parse(read(SETTINGS(d))).hooks.UserPromptSubmit && !existsSync(RULES(d)));
  const dry = await tap(d, ['init', 'claude', '--mode', 'pull', '--dry-run']); assert.equal(dry.code, 0); assert.match(dry.out, /mode ask/); assert.match(dry.out, /write the skill note/); assert.ok(!existsSync(RULES(d)));
  const p = await tap(d, ['init', 'claude', '--mode', 'pull']); assert.equal(p.code, 0);
  assert.ok(existsSync(RULES(d))); const s = JSON.parse(read(SETTINGS(d)));
  assert.equal(s.hooks.UserPromptSubmit, undefined); assert.deepEqual(s.hooks.Stop[0].hooks[0].command, 'echo bye'); assert.deepEqual(s.permissions, { allow: ['Bash(ls)'] });
  const notes = read(RULES(d)); await tap(d, ['init', 'claude', '--mode', 'pull']); assert.equal(read(RULES(d)), notes);
  await tap(d, ['init', 'claude', '--mode', 'hook']);
  assert.ok(!existsSync(RULES(d))); assert.ok(JSON.parse(read(SETTINGS(d))).hooks.UserPromptSubmit); assert.deepEqual(JSON.parse(read(SETTINGS(d))).hooks.Stop[0].hooks[0].command, 'echo bye');
  const bad = await tap(d, ['init', 'claude', '--mode', 'push']); assert.equal(bad.code, 2); assert.match(bad.err, /--mode must be auto or ask/);
});

test('[claude-code-pull R2] the generated note lists every skill with its description and no skill instruction text', async () => {
  const d = project(); await tap(d, ['init', 'claude', '--mode', 'pull']);
  const note = read(RULES(d));
  assert.match(note, /^<!-- Generated by `nib init claude --mode ask`/); assert.match(note, /- acme-sql-style: Acme's SQL style guide for analytics queries\./);
  assert.equal((note.match(/^- acme-/gm) ?? []).length, 5); assert.ok(note.length < 3000);
  assert.ok(!note.includes('-- checked') && !note.includes('[ACME-RN]'));
  const again = project(); await tap(again, ['init', 'claude', '--mode', 'pull']); assert.equal(read(RULES(again)).replace(/"[^"]*nib\.js"/g, 'X'), note.replace(/"[^"]*nib\.js"/g, 'X'));
});

test('[claude-code-pull R3] CLAUDE.md, CLAUDE.local.md and AGENTS.md are never created, edited or deleted, with and without an AGENTS.md', async () => {
  for (const extra of [{ 'AGENTS.md': '# Agents\nproject rules\n' }, {}, { 'AGENTS.md': 'a', 'CLAUDE.md': 'c', 'CLAUDE.local.md': 'l' }]) {
    const d = project(extra), before = instr(d);
    await tap(d, ['init', 'claude', '--mode', 'pull']); assert.deepEqual(instr(d), before);
    await tap(d, ['init', 'claude', '--mode', 'hook']); assert.deepEqual(instr(d), before);
    await tap(d, ['init', 'claude', '--mode', 'pull']); await tap(d, ['init', 'claude', '--undo']); assert.deepEqual(instr(d), before);
    assert.ok(!readdirSync(d).includes('CLAUDE.md') || 'CLAUDE.md' in extra);
  }
});

test('[claude-code-pull R4] the note says "nib" only when tap on the PATH is this installation, otherwise an absolute node command with a warning', async () => {
  const d = project(), bindir = mkdtempSync(join(tmpdir(), 'bin-')); symlinkSync(bin, join(bindir, 'nib'));
  const abs = await tap(d, ['init', 'claude', '--mode', 'pull']);
  assert.match(read(RULES(d)), new RegExp(`run \`node "${bin.replace(/[/.]/g, '\\$&')}" ask`)); assert.match(abs.out, /machine-specific path.*do not commit/);
  const short = await tap(d, ['init', 'claude', '--mode', 'pull'], { env: { GITHUB_TOKEN: '', HOME: join(d, '.nohome'), PATH: `${bindir}:/usr/bin` } });
  assert.match(read(RULES(d)), /run `nib ask "<what you need to know>"`/); assert.ok(!/machine-specific/.test(short.out));
  const other = mkdtempSync(join(tmpdir(), 'bin-')); mkdirSync(join(other, 'x')); writeFileSync(join(other, 'nib'), '#!/bin/sh\n', { mode: 0o755 });
  await tap(d, ['init', 'claude', '--mode', 'pull'], { env: { GITHUB_TOKEN: '', HOME: join(d, '.nohome'), PATH: `${other}:/usr/bin` } });
  assert.match(read(RULES(d)), /node ".*nib\.js" ask/);
});

